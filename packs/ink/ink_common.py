# grape: falls from z0 at grape0 and lands at z1 at grape_land (constant acceleration)
GR_Z0, GR_Z1 = 92.0, 2.4
GR_G = 2 * (GR_Z0 - GR_Z1) / (EV["grape_land"] - EV["grape0"]) ** 2
def grape_z(t):
    if t <= EV["grape0"]: return GR_Z0
    if t >= EV["grape_land"]: return GR_Z1
    return GR_Z0 - 0.5 * GR_G * (t - EV["grape0"]) ** 2

def _zoom_keys():   # cartridge -> nozzle plate, exponential approach
    ks = []
    t0, t1 = 20.8, 25.3
    for i in range(13):
        u = i / 12
        t = t0 + (t1 - t0) * u
        e = (1 - math.cos(math.pi * min(1.0, u * 1.08))) / 2   # ease, lands slightly early
        d = 60.0 * (0.6 / 60.0) ** e
        tz = 0.0 + 4.82 * min(1.0, e * 1.25)
        ks.append((t, (0.12 * (1 - d / 60), -d, tz - d * 0.32), (0.0, 0.0, tz), 35 + 15 * e))
    return ks

