def crossings(t0, t1):
    """times a drop passes the focus z=0 between t0 and t1"""
    out = []
    n0 = int(math.floor((BASE0 - V * t1) / SP)) - 1
    n1 = int(math.ceil((BASE0 - V * t0) / SP)) + 1
    for n in range(n0, n1 + 1):
        tc = (BASE0 - SP * n) / V
        if t0 <= tc <= t1:
            out.append(tc)
    return sorted(out)

